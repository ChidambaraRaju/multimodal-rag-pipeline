"""Answer a question from the ingested document.

Steps: retrieve the most relevant chunks from Chroma, then send their original text,
tables and images to the generation model.

Use answer_question() from other code, for example an API endpoint.
Run this file alone to try the test questions:  python -m multimodal_rag.generate
All settings live in config.py. Run ingest.py first so the vector store exists.
"""

import json

from langchain_core.messages import HumanMessage
from langchain_groq import ChatGroq

from multimodal_rag import config
from multimodal_rag.store import open_vector_store

# The last question is not covered by the first 6 pages, to check the model says so instead of guessing
TEST_QUESTIONS = [
    "How many attention heads does the Transformer use, and what is the dimension of each head?",
    "What are the two main components of the Transformer architecture, and what sub-layers does each contain?",
    "How does the complexity per layer of self-attention compare with recurrent and convolutional layers?",
    "Which optimizer and learning rate schedule were used to train the Transformer?",
]

ANSWER_PROMPT = """Based on the following documents, please answer this question: {question}

CONTENT TO ANALYZE:
{documents}
Please provide a clear, comprehensive answer using the text, tables, and images above. If the documents don't contain sufficient information to answer the question, say "I don't have enough information to answer that question based on the provided documents."

ANSWER:"""


def retrieve_chunks(question):
    """Find the chunks most relevant to the question. Each chunk carries its original text, tables and images."""
    results = open_vector_store().similarity_search_with_relevance_scores(question, k=config.RETRIEVED_CHUNK_COUNT)

    chunks = []
    for document, score in results:
        original_content = json.loads(document.metadata["original_content"])
        chunks.append(
            {
                "score": score,  # 0 to 1, higher is more relevant
                "text": original_content["raw_text"],
                "tables_html": original_content["tables_html"],
                "images_base64": original_content["images_base64"],
            }
        )
    return chunks


def generate_answer(question, chunks):
    """Ask the generation model to answer from the chunks. Returns the answer and the name of the model that wrote it."""
    documents_text = ""
    for number, chunk in enumerate(chunks, start=1):
        documents_text += f"--- Document {number} ---\nTEXT:\n{chunk['text']}\n\n"
        for table_number, table in enumerate(chunk["tables_html"], start=1):
            documents_text += f"Table {table_number}:\n{table}\n\n"

    content = [{"type": "text", "text": ANSWER_PROMPT.format(question=question, documents=documents_text)}]
    for chunk in chunks:
        for image in chunk["images_base64"]:
            content.append({"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{image}"}})

    # reasoning_format="parsed" keeps the model's thinking out of the answer text
    llm = ChatGroq(model=config.GENERATION_MODEL, temperature=0, reasoning_format="parsed")
    response = llm.invoke([HumanMessage(content=content)])
    return response.content, response.response_metadata.get("model_name", config.GENERATION_MODEL)


def answer_question(question):
    """Run retrieval and generation for one question."""
    chunks = retrieve_chunks(question)
    answer, model = generate_answer(question, chunks)
    return {"question": question, "answer": answer, "model": model, "chunks": chunks}


def print_result(result):
    """Show the retrieved chunks, the model and the answer in the terminal."""
    print("=" * 100)
    print(f"QUESTION: {result['question']}\n")

    for number, chunk in enumerate(result["chunks"], start=1):
        print(
            f"CHUNK {number}  score={chunk['score']:.3f}  "
            f"tables={len(chunk['tables_html'])}  images={len(chunk['images_base64'])}"
        )
        print(f"{chunk['text']}\n")

    print(f"GENERATED BY: {result['model']}\n")
    print(f"ANSWER:\n{result['answer']}\n")


def main():
    for question in TEST_QUESTIONS:
        print_result(answer_question(question))


if __name__ == "__main__":
    main()
